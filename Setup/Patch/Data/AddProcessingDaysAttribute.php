declare(strict_types=1);

namespace Ecommet\SmartDeliveryDate\Setup\Patch\Data;

use Ecommet\SmartDeliveryDate\Model\ProcessingTimeResolver;
use Magento\Catalog\Model\Product;
use Magento\Catalog\Model\ResourceModel\Eav\Attribute;
use Magento\Eav\Setup\EavSetupFactory;
use Magento\Framework\Setup\ModuleDataSetupInterface;
use Magento\Framework\Setup\Patch\DataPatchInterface;
use Magento\Framework\Setup\Patch\PatchRevertableInterface;

/**
 * Adds the per-product "Processing Time (days)" attribute
 */
class AddProcessingDaysAttribute implements DataPatchInterface, PatchRevertableInterface
{
    /**
     * @param ModuleDataSetupInterface $moduleDataSetup
     * @param EavSetupFactory $eavSetupFactory
     */
    public function __construct(
        private readonly ModuleDataSetupInterface $moduleDataSetup,
        private readonly EavSetupFactory $eavSetupFactory
    ) {
    }

    /**
     * @inheritdoc
     */
    public function apply(): self
    {
        $eavSetup = $this->eavSetupFactory->create(['setup' => $this->moduleDataSetup]);
        $eavSetup->addAttribute(
            Product::ENTITY,
            ProcessingTimeResolver::ATTRIBUTE_CODE,
            [
                'type' => 'int',
                'label' => 'Processing Time (days)',
                'input' => 'text',
                'frontend_class' => 'validate-digits validate-zero-or-greater',
                'note' => 'Overrides the Smart Delivery Date processing time for this product. '
                    . 'Leave empty to use the store configuration.',
                'required' => false,
                'global' => Attribute::SCOPE_GLOBAL,
                'visible' => true,
                'user_defined' => false,
                'searchable' => false,
                'filterable' => false,
                'comparable' => false,
                'visible_on_front' => false,
                'used_in_product_listing' => false,
                'is_used_in_grid' => true,
                'is_visible_in_grid' => false,
                'is_filterable_in_grid' => true,
                'group' => 'Smart Delivery Date',
                'sort_order' => 10,
            ]
        );

        return $this;
    }

    /**
     * @inheritdoc
     */
    public function revert(): void
    {
        $eavSetup = $this->eavSetupFactory->create(['setup' => $this->moduleDataSetup]);
        $eavSetup->removeAttribute(Product::ENTITY, ProcessingTimeResolver::ATTRIBUTE_CODE);
    }

    /**
     * @inheritdoc
     */
    public static function getDependencies(): array
    {
        return [];
    }

    /**
     * @inheritdoc
     */
    public function getAliases(): array
    {
        return [];
    }
}
